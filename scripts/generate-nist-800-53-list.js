#!/usr/bin/env node
// Generates api/controls/nist-800-53-rev5.js from NIST's OSCAL catalog.
//
//   node scripts/generate-nist-800-53-list.js <path-to-oscal-content-clone> [output-file]
//
// The clone is https://github.com/usnistgov/oscal-content (public domain,
// CC0). The script reads nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json
// and writes the list of current control IDs in the form people write them
// (AC-2, AC-2(1)), the official title, and the family. Withdrawn controls are
// kept out of the valid list and recorded separately. The source commit,
// tag, and catalog version are written into the output. Same input, same
// output: nothing in it depends on the date.

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const CATALOG_PATH = "nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json";
const REPO = "https://github.com/usnistgov/oscal-content";

// The label NIST prints in the standard: the one with no "class" (AC-2,
// AC-2(1)). The zero-padded and 800-53A labels carry a class.
function plainLabel(control) {
  const labels = (control.props || []).filter(function(p) { return p.name === "label" && !p.class; });
  if (labels.length !== 1) throw new Error("Expected exactly one plain label on " + control.id + ", found " + labels.length);
  return labels[0].value;
}

function isWithdrawn(control) {
  return (control.props || []).some(function(p) { return p.name === "status" && p.value === "withdrawn"; });
}

// OSCAL catalog (parsed JSON) -> { controls, withdrawn, source }. Throws on
// anything unexpected (nested deeper than enhancements, duplicate IDs).
function catalogToList(json) {
  const catalog = json.catalog;
  const controls = [];
  const withdrawn = [];
  const seen = new Set();

  function visit(control, family, depth) {
    if (depth > 1) throw new Error("Unexpected nesting below an enhancement at " + control.id);
    const id = plainLabel(control);
    if (seen.has(id)) throw new Error("Duplicate control ID " + id);
    seen.add(id);
    if (isWithdrawn(control)) withdrawn.push(id);
    else controls.push({ id: id, title: control.title, category: family });
    (control.controls || []).forEach(function(sub) { visit(sub, family, depth + 1); });
  }

  catalog.groups.forEach(function(group) {
    (group.controls || []).forEach(function(c) { visit(c, group.title, 0); });
  });

  return {
    controls: controls,
    withdrawn: withdrawn,
    catalog: {
      version: catalog.metadata.version,
      oscalVersion: catalog.metadata["oscal-version"],
      lastModified: catalog.metadata["last-modified"]
    }
  };
}

function git(cloneDir, args) {
  try {
    return execFileSync("git", ["-C", cloneDir].concat(args), { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch (e) {
    return null;
  }
}

function render(list, source) {
  const lines = [];
  lines.push("// GENERATED by scripts/generate-nist-800-53-list.js. Do not edit by hand.");
  lines.push("// Source: NIST OSCAL catalog for SP 800-53 Rev 5, " + source.repo + " (public domain, CC0).");
  lines.push("// Regenerate with: node scripts/generate-nist-800-53-list.js <path-to-oscal-content-clone>");
  lines.push("");
  lines.push("export default {");
  lines.push('  frameworkId: "NIST SP 800-53 Rev 5",');
  lines.push('  listStatus: "verified",');
  lines.push("  source: " + JSON.stringify(source, null, 2).replace(/\n/g, "\n  ") + ",");
  lines.push("  // Current controls and enhancements, written as NIST prints them: AC-2, AC-2(1).");
  lines.push("  controls: [");
  list.controls.forEach(function(c, i) {
    lines.push("    " + JSON.stringify(c) + (i < list.controls.length - 1 ? "," : ""));
  });
  lines.push("  ],");
  lines.push("  // Withdrawn in Rev 5. Not valid IDs; kept so the reason can be shown later.");
  lines.push("  withdrawn: [");
  list.withdrawn.forEach(function(id, i) {
    lines.push("    " + JSON.stringify(id) + (i < list.withdrawn.length - 1 ? "," : ""));
  });
  lines.push("  ]");
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function main(argv) {
  const cloneDir = argv[2];
  if (!cloneDir) {
    console.error("Usage: node scripts/generate-nist-800-53-list.js <path-to-oscal-content-clone> [output-file]");
    process.exit(1);
  }
  const out = argv[3] || path.join(__dirname, "..", "api", "controls", "nist-800-53-rev5.js");
  const json = JSON.parse(fs.readFileSync(path.join(cloneDir, CATALOG_PATH), "utf8"));
  const list = catalogToList(json);
  const source = {
    repo: REPO,
    commit: git(cloneDir, ["rev-parse", "HEAD"]),
    tag: git(cloneDir, ["describe", "--tags", "--exact-match"]),
    file: CATALOG_PATH,
    catalogVersion: list.catalog.version,
    oscalVersion: list.catalog.oscalVersion,
    lastModified: list.catalog.lastModified
  };
  if (!source.commit) throw new Error(cloneDir + " is not a git clone, so the source commit cannot be recorded.");
  fs.writeFileSync(out, render(list, source));
  console.log("Wrote " + out + ": " + list.controls.length + " controls, " + list.withdrawn.length + " withdrawn (catalog " + source.catalogVersion + ", commit " + source.commit.slice(0, 7) + ").");
}

if (require.main === module) main(process.argv);

module.exports = { catalogToList, plainLabel, isWithdrawn };
